/**
 * Format currency with symbol
 * @param {number} amount 
 * @param {string} symbol 
 * @returns {string}
 */
export function formatCurrency(amount, symbol = '$') {
  const num = Number(amount) || 0;
  // If integer, display without .00 unless small
  const isWhole = Number.isInteger(num);
  const formatted = Math.abs(num).toLocaleString('en-US', {
    minimumFractionDigits: isWhole ? 0 : 2,
    maximumFractionDigits: 2
  });
  
  if (num < 0) {
    return `-${symbol}${formatted}`;
  }
  return `${symbol}${formatted}`;
}

/**
 * Generate shareable text for WhatsApp / Telegram group chat
 */
export function generateShareText({ gameDate, currency, totalPot, transactions, playerStats }) {
  const dateStr = new Date(gameDate || Date.now()).toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric'
  });

  let text = `♠️♥️ POKER HOME GAME SETTLEMENT ♣️♦️\n`;
  text += `📅 ${dateStr}\n`;
  text += `💰 Total Pot: ${formatCurrency(totalPot, currency)}\n\n`;

  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `💸 WHO PAYS WHO (Minimum Transfers):\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;

  if (transactions.length === 0) {
    text += `Everyone broke even! No payments needed.\n`;
  } else {
    transactions.forEach((tx, i) => {
      text += `${i + 1}. *${tx.from}* ➔ *${tx.to}*: ${formatCurrency(tx.amount, currency)}\n`;
    });
  }

  text += `\n━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `📊 PLAYER LEADERBOARD (P/L):\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;

  playerStats.forEach((p, i) => {
    const medal = i === 0 && p.net > 0 ? '🏆 ' : p.net > 0 ? '🟢 ' : p.net < 0 ? '🔴 ' : '⚪ ';
    const netFormatted = p.net > 0 
      ? `+${formatCurrency(p.net, currency)}`
      : p.net < 0 
        ? `-${formatCurrency(Math.abs(p.net), currency)}`
        : `±${formatCurrency(0, currency)}`;
    text += `${medal}*${p.name}*: ${netFormatted} (In: ${formatCurrency(p.totalBuyIn, currency)} | Out: ${formatCurrency(p.finalChips, currency)})\n`;
  });

  text += `\nGenerated by Poker Home Game Manager 🃏`;
  return text;
}
